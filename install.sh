#!/usr/bin/env bash
# Open Workbench Studio installer (no sudo needed). Safe to run again: it only creates what is missing and
# re-syncs the Python environment to requirements.lock.
#
#   ./install.sh                  # venv + packages + `studio` command + desktop entry, then the Studio tests
#   ./install.sh --no-tests       # skip the test run
#   ./install.sh --systemd        # also install and enable the systemd user service (workbench-studio.service)
#   ./install.sh --no-desktop     # do not create the application-menu entry
#
# Environment: PYTHON_VERSION (default 3.13), BIN_DIR (default ~/.local/bin), STUDIO_HOME, STUDIO_WORK_DIR.
set -euo pipefail

S="$(cd "$(dirname "$0")" && pwd)"
PY_VER="${PYTHON_VERSION:-3.13}"
BIN="${BIN_DIR:-$HOME/.local/bin}"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE="${STUDIO_HOME:-$DATA_HOME/workbench-studio}"
WORK="${STUDIO_WORK_DIR:-$STATE/output}"
APPS="$DATA_HOME/applications"
ICONS="$DATA_HOME/icons/hicolor/scalable/apps"

RUN_TESTS=1 SYSTEMD=0 DESKTOP=1
for a in "$@"; do
  case "$a" in
    --no-tests) RUN_TESTS=0 ;;
    --systemd) SYSTEMD=1 ;;
    --no-desktop) DESKTOP=0 ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) echo "unknown option: $a" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1m==> %s\033[0m\n' "$*"; }

if ! command -v uv >/dev/null 2>&1; then
  echo "uv was not found. Install it first (user-level, no sudo):" >&2
  echo "  curl -LsSf https://astral.sh/uv/install.sh | sh" >&2
  echo "then open a new terminal (or: source ~/.local/bin/env) and run ./install.sh again." >&2
  exit 1
fi

say "Python $PY_VER and virtual environment ($S/.venv)"
uv python install "$PY_VER"
[ -x "$S/.venv/bin/python" ] || uv venv --python "$PY_VER" "$S/.venv"

say "Dependencies (requirements.lock)"
uv pip install --python "$S/.venv" -r "$S/requirements.lock"
for p in workbench-core workbench-kaligraf workbench-glow workbench-maker workbench-topo .; do
  uv pip install --python "$S/.venv" --no-deps -e "$S/$p"
done

say "Folders"
mkdir -p "$BIN" "$STATE" "$WORK" "$CONFIG_HOME/workbench-maker" "$CONFIG_HOME/workbench-glow"
if [ ! -e "$STATE/renk_paleti.yaml" ] && [ -z "${WORKBENCH_PALETTE:-}" ]; then
  cp "$S/examples/palette.example.yaml" "$STATE/renk_paleti.yaml"
  echo "example filament palette copied to $STATE/renk_paleti.yaml (edit it, or tune colours on /kartela)"
fi

say "Command: $BIN/studio"
cat > "$BIN/studio" <<SH
#!/bin/sh
# generated by $S/install.sh
export PYTHONNOUSERSITE=1
: "\${STUDIO_HOME:=$STATE}"
: "\${STUDIO_WORK_DIR:=$WORK}"
export STUDIO_HOME STUDIO_WORK_DIR
exec "$S/.venv/bin/python" -m studio.cli "\$@"
SH
chmod +x "$BIN/studio"
case ":$PATH:" in *":$BIN:"*) ;; *) echo "note: $BIN is not on your PATH; add it (e.g. in ~/.profile)." ;; esac

if [ "$DESKTOP" = 1 ]; then
  say "Application menu entry"
  mkdir -p "$APPS" "$ICONS"
  cp "$S/src/studio/web/studio.svg" "$ICONS/workbench-studio.svg"
  cat > "$APPS/workbench-studio.desktop" <<DESK
[Desktop Entry]
Type=Application
Name=Open Workbench Studio
Comment=Parametric 3D models for your printer: signs, light boxes, maps and more
Exec=$BIN/studio open
Icon=workbench-studio
Terminal=false
Categories=Graphics;3DGraphics;
Actions=stop;

[Desktop Action stop]
Name=Stop Studio
Exec=$BIN/studio stop
DESK
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$APPS" >/dev/null 2>&1 || true
  command -v gtk-update-icon-cache >/dev/null 2>&1 && gtk-update-icon-cache -q -t "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
fi

if [ "$SYSTEMD" = 1 ]; then
  say "systemd user service: workbench-studio.service"
  UNIT_DIR="$CONFIG_HOME/systemd/user"
  mkdir -p "$UNIT_DIR"
  sed -e "s|@REPO@|$S|g" -e "s|@STATE@|$STATE|g" -e "s|@WORK@|$WORK|g" \
    "$S/deploy/workbench-studio.service" > "$UNIT_DIR/workbench-studio.service"
  systemctl --user daemon-reload
  systemctl --user enable --now workbench-studio.service
  systemctl --user --no-pager --lines=0 status workbench-studio.service || true
fi

if command -v orcaslicer >/dev/null 2>&1 || command -v orca-slicer >/dev/null 2>&1 || [ -n "${WORKBENCH_ORCA:-}" ]; then
  echo "OrcaSlicer: found"
else
  echo "OrcaSlicer: not found (optional; needed for --slice / studio kontrol / print_check). See docs/install.md."
fi

if [ "$RUN_TESTS" = 1 ]; then
  say "Studio tests"
  PYTHONNOUSERSITE=1 "$S/.venv/bin/python" -m pytest -q -p no:cacheprovider "$S/tests"
fi

say "Done. Start with: studio ui   (http://127.0.0.1:7870, MCP at /mcp/)  or: studio open"
